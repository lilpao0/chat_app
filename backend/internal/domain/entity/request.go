package entity

import "errors"

var ErrRequestConflict = errors.New("request ID already used for another message")

// ValidRequestID accepts a canonical lowercase UUID without adding a transport dependency.
func ValidRequestID(s string) bool {
	if len(s) != 36 {
		return false
	}
	for i, c := range s {
		if i == 8 || i == 13 || i == 18 || i == 23 {
			if c != '-' {
				return false
			}
			continue
		}
		if !(c >= '0' && c <= '9' || c >= 'a' && c <= 'f') {
			return false
		}
	}
	return true
}
